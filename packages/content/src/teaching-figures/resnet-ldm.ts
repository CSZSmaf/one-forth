const text = (
  x: number,
  y: number,
  value: string,
  tone: DiagramTone = "ink",
  size = 18,
): DiagramElement => ({ kind: "text", x, y, text: value, size, tone });
const math = (
  x: number,
  y: number,
  width: number,
  latex: string,
  label: string,
  tone: DiagramTone = "ink",
  height = 36,
): DiagramElement => ({
  kind: "math",
  x,
  y,
  width,
  height,
  latex,
  label,
  tone,
  size: 18,
  align: "center",
});
const box = (
  x: number,
  y: number,
  width: number,
  height: number,
  tone: DiagramTone = "ink",
): DiagramElement => ({ kind: "rect", x, y, width, height, tone, fill: "tint" });
const arrow = (
  x1: number,
  y1: number,
  x2: number,
  y2: number,
  tone: DiagramTone = "ink",
): DiagramElement => ({ kind: "line", x1, y1, x2, y2, tone, arrow: true });
const route = (d: string, tone: DiagramTone = "ink", dashed = false): DiagramElement => ({
  kind: "path",
  d,
  tone,
  dashed,
  fill: "none",
  arrow: true,
});
const panel = (
  title: string,
  description: string,
  elements: readonly DiagramElement[],
): TeachingFigurePanel => ({ title, description, width: 320, height: 440, elements });

