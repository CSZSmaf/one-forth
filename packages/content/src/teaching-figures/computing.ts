import type {
  DiagramElement,
  DiagramTone,
  TeachingFigureData,
  TeachingFigurePanel,
} from "@one-forth/registry";

const text = (x: number, y: number, value: string, tone: DiagramTone = "ink"): DiagramElement => ({
  kind: "text",
  x,
  y,
  text: value,
  anchor: "middle",
  size: 19,
  tone,
});
const math = (
  x: number,
  y: number,
  width: number,
  latex: string,
  label: string,
  tone: DiagramTone = "ink",
): DiagramElement => ({
  kind: "math",
  x,
  y,
  width,
  height: 46,
  latex,
  label,
  align: "center",
  size: 19,
  tone,
});
const line = (
  x1: number,
  y1: number,
  x2: number,
  y2: number,
  tone: DiagramTone = "ink",
  arrow = false,
  dashed = false,
): DiagramElement => ({ kind: "line", x1, y1, x2, y2, tone, arrow, dashed });
const rect = (
  x: number,
  y: number,
  width: number,
  height: number,
  tone: DiagramTone = "ink",
  fill: "none" | "surface" | "tint" | "solid" = "none",
): DiagramElement => ({ kind: "rect", x, y, width, height, tone, fill });
const circle = (
  cx: number,
  cy: number,
  r: number,
  tone: DiagramTone = "input",
  fill: "none" | "surface" | "tint" | "solid" = "surface",
): DiagramElement => ({ kind: "circle", cx, cy, r, tone, fill });
const path = (
  d: string,
  tone: DiagramTone = "ink",
  arrow = false,
  dashed = false,
): DiagramElement => ({ kind: "path", d, tone, arrow, dashed });
const panel = (
  title: string,
  description: string,
  height: number,
  elements: readonly DiagramElement[],
): TeachingFigurePanel => ({ title, description, width: 320, height, elements });
const numberNode = (
  x: number,
  y: number,
  value: number,
  tone: DiagramTone = "input",
): readonly DiagramElement[] => [circle(x, y, 20, tone), text(x, y + 7, String(value), tone)];
const matrix = (
  x: number,
  y: number,
  values: readonly (readonly number[])[],
  cell: number,
  tone: DiagramTone,
): readonly DiagramElement[] =>
  values.flatMap((row, r) =>
    row.flatMap((value, c) => [
      rect(x + c * cell, y + r * cell, cell, cell, tone),
      text(x + (c + 0.5) * cell, y + (r + 0.5) * cell + 7, String(value), tone),
    ]),
  );

