interface ConceptSeed {
  readonly id: string;
  readonly title: string;
  readonly summary: string;
  readonly domain: string;
  readonly subject: string;
  readonly difficulty: number;
  readonly prerequisites: readonly string[];
  readonly recommendedPath: string;
  readonly aliases?: readonly string[];
}

type SeedTuple = readonly [
  id: string,
  title: string,
  summary: string,
  difficulty: number,
  prerequisites: readonly string[],
  aliases?: readonly string[],
];

function group(
  domain: string,
  subject: string,
  recommendedPath: string,
  entries: readonly SeedTuple[],
): readonly ConceptSeed[] {
  return entries.map(([id, title, summary, difficulty, prerequisites, aliases]) => ({
    id,
    title,
    summary,
    domain,
    subject,
    difficulty,
    prerequisites,
    recommendedPath,
    ...(aliases ? { aliases } : {}),
  }));
}

