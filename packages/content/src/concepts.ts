  readonly subject: string;
  /** Compatibility fields retained for callers that model cross-domain concepts. */
  readonly domains: readonly string[];
  readonly subjects: readonly string[];
  readonly difficulty: number;
  readonly aliases: readonly LocalizedText[];
  readonly prerequisites: readonly string[];
  readonly followUps: readonly string[];
  readonly relations: readonly KnowledgeRelation[];
  readonly recommendedPath: string;
  readonly maturity: EditorialStatus;
  /** @deprecated Compatibility projection; use maturity. */
  readonly readiness: ConceptReadiness;
  readonly estimatedMinutes: number;
  /** @deprecated Compatibility projection; use maturity. */
  readonly articleStatus: ConceptArticleStatus;
  readonly documents: readonly LocalizedDocumentReference[];
