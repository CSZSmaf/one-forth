const followUps = new Map<string, string[]>();
for (const seed of seeds) {
  for (const prerequisite of seed.prerequisites) {
    const current = followUps.get(prerequisite) ?? [];
    if (!current.includes(seed.id)) current.push(seed.id);
    followUps.set(prerequisite, current);
  }
}

const curriculumDocumentsByConcept = new Map<string, LocalizedDocumentReference[]>();
for (const chapter of curriculumData.chapters) {
  if (!chapter.contentId) continue;
  for (const conceptId of chapter.conceptIds) {
    const references = curriculumDocumentsByConcept.get(conceptId) ?? [];
    const documentId = `zh-CN/${chapter.contentId}`;
    if (!references.some((reference) => reference.documentId === documentId)) {
      references.push({ locale: "zh-CN", documentId });
    }
    curriculumDocumentsByConcept.set(conceptId, references);
  }
}

const curriculumChapterById = new Map(
  curriculumData.chapters.map((chapter) => [chapter.id, chapter] as const),
);

function outlineFor(seed: ConceptSeed): readonly LocalizedText[] {
  const required = requiredOutlineById.get(seed.id);
  if (required) return required.map((section) => ({ "zh-CN": section }));
  return [];
}

export const conceptCatalog: readonly ConceptEntity[] = seeds.map((seed) => {
  const next = followUps.get(seed.id) ?? [];
  const authoredArticle = articleReferences[seed.id];
  const curriculumDocuments = curriculumDocumentsByConcept.get(seed.id) ?? [];
  const canonicalLocation = canonicalLocationForConcept(seed.id, seed.domain, seed.subject);
  const canonicalChapter = curriculumChapterById.get(canonicalLocation.chapterId);
  const canonicalDocument = canonicalChapter?.contentId
    ? ({
        locale: "zh-CN" as const,
        documentId: `zh-CN/${canonicalChapter.contentId}`,
      } satisfies LocalizedDocumentReference)
    : undefined;
  const documents = [
    ...(authoredArticle
      ? [{ locale: "zh-CN" as const, documentId: authoredArticle.documentId }]
      : []),
    ...curriculumDocuments,
    ...(canonicalDocument ? [canonicalDocument] : []),
  ].filter(
    (reference, index, references) =>
      references.findIndex(
        (candidate) =>
          candidate.locale === reference.locale && candidate.documentId === reference.documentId,
      ) === index,
  );
  // Publication readiness follows the bound source document. Human review remains
  // separate and is never inferred from a generated concept record.
  const maturity = deriveConceptMaturity(
    canonicalChapter?.contentId ? [canonicalChapter.editorialStatus] : [],
    false,
  );
  const readiness: ConceptReadiness =
    maturity === "reviewed" || maturity === "verified"
      ? "reviewed"
      : maturity === "checked"
        ? "checked"
        : maturity === "draft"
          ? "draft-available"
          : maturity === "outline"
            ? "outlined"
            : "cataloged";
  const articleStatus: ConceptArticleStatus =
    maturity === "reviewed" || maturity === "verified"
      ? "reviewed"
      : maturity === "checked"
        ? "checked"
        : maturity === "draft"
          ? "draft"
          : "planned";
  return migrateConceptV1ToV2({
    schemaVersion: 1,
    id: seed.id,
    title: { "zh-CN": seed.title },
    summary: { "zh-CN": seed.summary },
    outline: outlineFor(seed),
    domain: seed.domain,
    subject: seed.subject,
    domains: [seed.domain],
    subjects: [seed.subject],
    difficulty: seed.difficulty,
    aliases: (seed.aliases ?? []).map((alias) => ({ "zh-CN": alias })),
    prerequisites: [...seed.prerequisites],
    followUps: [...next],
    // Prerequisites are the catalog's canonical graph edges. Semantic relations
    // belong to reviewed document metadata instead of being inferred from order.
    relations: [],
    recommendedPath: seed.recommendedPath,
    maturity,
    readiness,
    estimatedMinutes: 45 + seed.difficulty * 15,
    articleStatus,
    documents,
  });
});

export const conceptById: ReadonlyMap<string, ConceptEntity> = new Map(
  conceptCatalog.map((concept) => [concept.id, concept] as const),
);
