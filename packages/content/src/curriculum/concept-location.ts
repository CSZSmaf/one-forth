export function canonicalLocationForConcept(
  id: string,
  _domain: string,
  subject: string,
): CanonicalLocation {
  const primary = primaryArticleLocations[id];
  if (primary) return { chapterId: primary };
  const semantic = semanticConceptLocations[id];
  if (semantic) return semantic;
  const rule = rules.find((entry) => entry.subject === subject && entry.pattern.test(id));
  const chapterId = rule?.chapterId ?? subjectDefaults[subject];
  if (!chapterId) {
    throw new Error(`No curriculum chapter mapping for concept ${id} (${subject})`);
  }
  return { chapterId, anchorId: "article-overview" };
}

