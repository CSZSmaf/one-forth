export function graphConceptTitle(
  conceptId: string,
  fallback: string,
  locale: "zh-CN" | "en",
): string | null {
  if (teachingEntries.has(conceptId)) return null;
  return graphLabels[conceptId]?.[locale === "en" ? 1 : 0] ?? fallback;
}

export function presentGraphConcepts<
  T extends { readonly sourceId: string; readonly title: string },
>(entries: readonly T[], locale: "zh-CN" | "en"): T[] {
  return entries.flatMap((entry) => {
    const title = graphConceptTitle(entry.sourceId, entry.title, locale);
    return title === null ? [] : [{ ...entry, title }];
  });
}
